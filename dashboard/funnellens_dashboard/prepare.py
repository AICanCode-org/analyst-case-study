"""`prepare`: validate an answers.json, then write what the app serves from static/:
answers.json (copy), narrative.json (AI narrator or template) and onepager.md (the decision memo)."""

from __future__ import annotations

import json
import os
from pathlib import Path

import jsonschema

from .facts import RECOMMENDATION_LABELS, build_facts
from .narrator import Settings, narrate

HERE = Path(__file__).resolve().parent
SCHEMA_CANDIDATES = [
    Path(os.environ.get("ANSWERS_SCHEMA", "/nonexistent")),
    HERE.parents[1] / "contract" / "answers.schema.json",  # repo checkout
    HERE.parent / "contract" / "answers.schema.json",  # Docker image (/app/contract)
]


class AnswersError(Exception):
    """The answers file is missing, not JSON, or does not match the schema."""


def schema_path() -> Path:
    for path in SCHEMA_CANDIDATES:
        if path.is_file():
            return path
    raise AnswersError("answers.schema.json not found (set ANSWERS_SCHEMA)")


def load_answers(path: str | os.PathLike) -> dict:
    try:
        answers = json.loads(Path(path).read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise AnswersError(f"{path} not found: run a track pipeline first (make run)") from exc
    except json.JSONDecodeError as exc:
        raise AnswersError(f"{path} is not JSON: {exc}") from exc
    schema = json.loads(schema_path().read_text(encoding="utf-8"))
    try:
        jsonschema.validate(answers, schema)
    except jsonschema.ValidationError as exc:
        raise AnswersError(f"{path} does not match answers.schema.json: {exc.message}") from exc
    return answers


def onepager(answers: dict, narrative: dict) -> str:
    facts = build_facts(answers)
    ds = answers["dataset"]
    rec = answers["decision"]["recommendation"]
    lines = [
        "# FunnelLens decision memo",
        "",
        f"**Export** {ds['export']} ({ds['period_start']} to {ds['period_end']}), contract {ds['contract_version']}, "
        f"generated by the {answers['generator']['track']} track.",
        "",
        f"## Recommendation: {RECOMMENDATION_LABELS[rec]}",
        "",
        "Reasons: " + ", ".join(f"`{r}`" for r in answers["decision"]["reasons"]),
        "",
        "## Summary",
        "",
        narrative["text"],
        "",
        f"_Summary source: {narrative['source']}"
        + (f" (fallback: {narrative['reason']})" if narrative["fallback"] else "")
        + "._",
        "",
        "## Facts",
        "",
        *[f"- [{f.id}] {f.text}" for f in facts],
        "",
    ]
    return "\n".join(lines)


def prepare(answers_path: str | os.PathLike, out_dir: str | os.PathLike, settings: Settings | None = None) -> dict:
    answers = load_answers(answers_path)
    narrative = narrate(answers, settings).to_dict()
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    (out / "answers.json").write_text(json.dumps(answers, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "narrative.json").write_text(json.dumps(narrative, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (out / "onepager.md").write_text(onepager(answers, narrative), encoding="utf-8")
    return narrative
